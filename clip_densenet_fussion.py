"""### 6.1 Define Training Functions"""

def train_one_epoch(model, data_loader, criterion, optimizer, device):
    """
    Train the model for one epoch.

    Args:
        model: The model to train
        data_loader: DataLoader for training data
        criterion: Loss function
        optimizer: Optimizer
        device: Device to run on

    Returns:
        Average loss and accuracy for the epoch
    """
    model.train()
    running_loss = 0.0
    correct = 0
    total = 0

    progress_bar = tqdm(data_loader, desc="Training", leave=False)

    for batch_idx, (images, labels) in enumerate(progress_bar):
        img_cnn = images['cnn'].to(device)
        img_clip = images['clip'].to(device)
        labels = labels.to(device)

        optimizer.zero_grad()

        outputs = model(img_cnn, img_clip)
        loss = criterion(outputs, labels)

        loss.backward()

        # Gradient clipping
        torch.nn.utils.clip_grad_norm_(model.parameters(), max_norm=1.0)

        optimizer.step()

        running_loss += loss.item()
        _, predicted = torch.max(outputs.data, 1)
        total += labels.size(0)
        correct += (predicted == labels).sum().item()

        current_loss = running_loss / (batch_idx + 1)
        current_acc = 100. * correct / total
        progress_bar.set_postfix({
            'loss': f'{current_loss:.4f}',
            'acc': f'{current_acc:.2f}%'
        })

    epoch_loss = running_loss / len(data_loader)
    epoch_acc = 100. * correct / total

    return epoch_loss, epoch_acc


def validate(model, data_loader, criterion, device):
    """
    Validate the model.

    Args:
        model: The model to validate
        data_loader: DataLoader for validation data
        criterion: Loss function
        device: Device to run on

    Returns:
        Average loss, accuracy, and predictions
    """
    model.eval()
    running_loss = 0.0
    all_predictions = []
    all_labels = []

    with torch.no_grad():
        progress_bar = tqdm(data_loader, desc="Validation", leave=False)

        for images, labels in progress_bar:
            img_cnn = images['cnn'].to(device)
            img_clip = images['clip'].to(device)
            labels = labels.to(device)

            outputs = model(img_cnn, img_clip)
            loss = criterion(outputs, labels)

            running_loss += loss.item()
            _, predicted = torch.max(outputs.data, 1)

            all_predictions.extend(predicted.cpu().numpy())
            all_labels.extend(labels.cpu().numpy())

    epoch_loss = running_loss / len(data_loader)
    epoch_acc = accuracy_score(all_labels, all_predictions) * 100

    return epoch_loss, epoch_acc, all_predictions, all_labels

